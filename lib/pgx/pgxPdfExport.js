// /app/lib/pgx/pgxPdfExport.js
// Generates a one-page "Bring to Pharmacy" PDF summarising the user's
// PGx phenotype snapshot. Built entirely client-side via jsPDF — no
// server round-trip so it works offline.

import { jsPDF } from 'jspdf'
import { getPgxPlainEnglish } from '@/lib/pgxPlainEnglish'

const MARGIN = 40  // pt
const LINE   = 14  // default line-height pt

function severityColor(sev) {
  if (sev === 'critical')     return [196, 88, 32]   // #C45820
  if (sev === 'intermediate') return [180, 83, 9]    // #B45309
  return [46, 125, 50]                                // #2E7D32 green
}

function drawWrappedText(doc, text, x, y, maxW, lineHeight = LINE) {
  const lines = doc.splitTextToSize(text, maxW)
  doc.text(lines, x, y)
  return y + lines.length * lineHeight
}

// Very small drug catalog lookup for the pharmacy sheet — accepts any
// object with { primaryGene, extraGenes } fields (matches DRUG_CATALOG).
function drugsForGene(drugCatalog, gene) {
  return (drugCatalog || []).filter(
    (d) => !d.isHarmReduction && (d.primaryGene === gene || d.extraGenes?.includes(gene)),
  )
}

export function generatePgxPdf({ phenotypes, drugCatalog, patientName = null, medications = [] }) {
  const doc = new jsPDF({ unit: 'pt', format: 'letter' })
  const pageW = doc.internal.pageSize.getWidth()
  const contentW = pageW - MARGIN * 2
  let y = MARGIN

  // ─── Header ──────────────────────────────────────────────────────
  doc.setFont('helvetica', 'bold').setFontSize(18).setTextColor(27, 71, 77) // ss-teal
  doc.text('Pharmacogenomic (PGx) Phenotype Snapshot', MARGIN, y); y += 22
  doc.setFont('helvetica', 'normal').setFontSize(9).setTextColor(120, 120, 120)
  doc.text('Generated by SelfScience · Educational summary — not a clinical PGx test', MARGIN, y); y += 12
  const dateStr = new Date().toLocaleString('en-US', { dateStyle: 'medium', timeStyle: 'short' })
  doc.text(`Generated: ${dateStr}`, MARGIN, y); y += 16
  if (patientName) {
    doc.setFont('helvetica', 'bold').setFontSize(10).setTextColor(30, 30, 30)
    doc.text(`Patient: ${patientName}`, MARGIN, y); y += 14
  }

  // Separator
  doc.setDrawColor(200, 200, 200).setLineWidth(0.5)
  doc.line(MARGIN, y, pageW - MARGIN, y); y += 16

  // ─── Phenotype table ─────────────────────────────────────────────
  const genes = ['CYP2C19', 'CYP2D6', 'CYP2C9', 'VKORC1', 'SLCO1B1', 'DPYD', 'TPMT']

  for (const gene of genes) {
    const ph = phenotypes?.[gene]
    if (!ph) continue
    const { severity, impact } = getPgxPlainEnglish(gene, ph)
    const [r, g, b] = severityColor(severity)

    if (y > 720) { doc.addPage(); y = MARGIN }

    // Left severity stripe
    doc.setFillColor(r, g, b)
    doc.rect(MARGIN, y - 10, 3, 44, 'F')

    // Gene + phenotype header
    doc.setFont('helvetica', 'bold').setFontSize(12).setTextColor(27, 71, 77)
    doc.text(gene, MARGIN + 12, y)
    doc.setFont('helvetica', 'normal').setFontSize(10).setTextColor(30, 30, 30)
    doc.text(`— ${ph.label}`, MARGIN + 60, y)

    // Severity chip (right-aligned)
    const chipText = severity === 'critical'     ? 'DISCUSS'
                    : severity === 'intermediate' ? 'MONITOR'
                    :                                'STANDARD'
    doc.setFont('helvetica', 'bold').setFontSize(8).setTextColor(r, g, b)
    doc.text(chipText, pageW - MARGIN, y, { align: 'right' })
    y += 14

    // Impact line
    if (impact) {
      doc.setFont('helvetica', 'italic').setFontSize(9).setTextColor(80, 80, 80)
      y = drawWrappedText(doc, impact, MARGIN + 12, y, contentW - 12, 11)
    }

    // Drugs affected
    const drugs = drugsForGene(drugCatalog, gene)
    if (drugs.length) {
      const names = drugs.slice(0, 12).map((d) => d.generic).join(', ')
      doc.setFont('helvetica', 'bold').setFontSize(8).setTextColor(60, 60, 60)
      doc.text('Drugs affected:', MARGIN + 12, y + 4); y += 4
      doc.setFont('helvetica', 'normal').setFontSize(8).setTextColor(90, 90, 90)
      y = drawWrappedText(doc, names + (drugs.length > 12 ? ` (+${drugs.length - 12} more)` : ''),
        MARGIN + 12, y + 10, contentW - 12, 10)
    }

    y += 12
  }

  // ─── Current medications (optional) ─────────────────────────────
  if (medications?.length) {
    if (y > 700) { doc.addPage(); y = MARGIN }
    doc.setDrawColor(200, 200, 200).line(MARGIN, y, pageW - MARGIN, y); y += 14
    doc.setFont('helvetica', 'bold').setFontSize(11).setTextColor(27, 71, 77)
    doc.text('Current medications (patient-provided)', MARGIN, y); y += 14
    doc.setFont('helvetica', 'normal').setFontSize(10).setTextColor(30, 30, 30)
    for (const m of medications) {
      const line = `• ${m.name}${m.primaryGene ? `  (PGx-relevant: ${m.primaryGene})` : ''}`
      y = drawWrappedText(doc, line, MARGIN + 6, y, contentW - 6, 12)
    }
    y += 8
  }

  // ─── Footer disclaimer ───────────────────────────────────────────
  if (y > 720) { doc.addPage(); y = MARGIN }
  doc.setDrawColor(200, 200, 200).line(MARGIN, y, pageW - MARGIN, y); y += 12
  doc.setFont('helvetica', 'italic').setFontSize(8).setTextColor(120, 120, 120)
  const disclaimer = 'This report is generated from educational genome interpretation tools and is not a clinical diagnostic test. Consult a qualified healthcare provider before making any medical decisions. Findings are based on best-available published pharmacogenomics evidence at time of generation.'
  drawWrappedText(doc, disclaimer, MARGIN, y, contentW, 10)

  return doc
}

export function downloadPgxPdf(payload) {
  const doc = generatePgxPdf(payload)
  const dateStr = new Date().toISOString().slice(0, 10)
  doc.save(`SelfScience-PGx-Report-${dateStr}.pdf`)
}
