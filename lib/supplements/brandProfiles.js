export function slugifyBrand(name) {
  return String(name || '').toLowerCase().replace(/\s+/g, ' ').replace(/[^a-z0-9\s\-']/g, '').trim()
}

export function getBrandProfile(brandName) {
  const key = slugifyBrand(brandName)
  return BRAND_PROFILES[key] || null
}

// Convenience: given a brand name, resolve programme IDs to full registry rows.
export function getBrandProgrammeBadges(brandName) {
  const profile = getBrandProfile(brandName)
  if (!profile?.programmes) return []
  return profile.programmes.map((id) => ({ ...CERT_REGISTRY[id], source: 'brand' })).filter((c) => c.id)
}
