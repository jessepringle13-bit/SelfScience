// /lib/genomeParser.js
// SelfScience Step 1 — client-side 23andMe text-file parser.
//
// This is the *text-based* parser used by the new two-step classification
// engine. It differs from the older /lib/genome-parser.js (which accepts a
// File object and also unzips archives) in that it accepts already-decoded
// string content — useful when the caller has already read a file into
// memory or is running the parser server-side on a text blob.
//
// SECURITY: this function is safe to run in either environment because it
// touches only the string it was handed and never performs I/O. In the
// browser the raw genome content stays in-tab; no bytes are transmitted.

import { VARIANT_LIST } from './variants'

/**
 * Parse a 23andMe v3/v4/v5 raw data text file.
 * Runs entirely from the string content — no network / no filesystem.
 * Returns only rsIDs present in our curated VARIANT_LIST.
 *
 * @param {string} fileContent  Raw text of a 23andMe / AncestryDNA export.
 * @returns {Record<string,string>} Map of rsid → genotype (uppercase).
 */
export function parseGenomeFile(fileContent) {
  const result = {}
  const variantSet = new Set(VARIANT_LIST)

  const lines = String(fileContent || '').split(/\r?\n/)

  for (const line of lines) {
    // Skip comment lines and blanks
    if (line.startsWith('#') || line.trim() === '') continue

    // 23andMe format: rsid \t chromosome \t position \t genotype
    const parts = line.split('\t')
    if (parts.length < 4) continue

    const rsid = parts[0].trim().toLowerCase()
    const genotype = parts[3].trim().toUpperCase()

    // Only keep variants we can classify
    if (!variantSet.has(rsid)) continue

    // Skip no-calls (- - / 00 / empty)
    if (genotype === '--' || genotype === '00' || genotype === '') continue

    result[rsid] = genotype
  }

  return result
}

/**
 * Sanity-check a raw genome text blob before parsing.
 *
 * @param {string} fileContent
 * @returns {{ valid: boolean, reason?: string, variantCount?: number }}
 */
export function validateGenomeFile(fileContent) {
  const s = String(fileContent || '')
  if (
    !s.includes('# This data file generated by 23andMe') &&
    !s.includes('rsid\tchromosome\tposition\tgenotype') &&
    !s.includes('rs')
  ) {
    return { valid: false, reason: 'File does not appear to be a 23andMe raw data file.' }
  }

  const lines = s.split(/\r?\n/).filter((l) => !l.startsWith('#') && l.trim())
  if (lines.length < 100) {
    return { valid: false, reason: 'File appears incomplete — fewer than 100 variant lines detected.' }
  }

  return { valid: true, variantCount: lines.length }
}
