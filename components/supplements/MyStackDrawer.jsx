'use client'

// /app/components/supplements/MyStackDrawer.jsx
// Slide-in drawer showing the user's supplement stack + Stack Quality
// aggregate + export options. Opens from a "My Stack (N)" trigger the
// supplements landing page mounts near the top nav.

import { useEffect, useMemo, useState } from 'react'
import Link from 'next/link'
import { X, Sparkles, Trash2, Copy, CheckCircle2, ExternalLink, AlertTriangle } from 'lucide-react'
import { stackStore, medicationsStore } from '@/lib/lists'
import { useListStore } from '@/lib/lists/store'
import { BRAND_PROFILES } from '@/lib/supplements/brandProfiles'
import { getBrandExtras, activeGenomeFormsFromContext } from '@/lib/supplements/brandExtras'
import { computeBrandScore, BRAND_SCORE_STYLE } from '@/utils/brandScore'
import { findInteractionsForSupplement } from '@/lib/supplements/interactions'
import { getGenomeResults } from '@/lib/genomeSession'
import { inferAllPGxPhenotypes } from '@/lib/pgxClassifier'

const COST_TO_MONTHLY = { '$': 15, '$$': 30, '$$$': 60 }

export default function MyStackDrawer({ open, onClose }) {
  const [items] = useListStore(stackStore)
  const [meds]  = useListStore(medicationsStore)
  const [copied, setCopied] = useState(false)
  const [context, setContext] = useState({ activeForms: [], phenotypes: null })

  useEffect(() => {
    if (!open) return
    const g = getGenomeResults()
    const variantsByGene = {}
    if (g) {
      for (const v of g.variants_recognized || []) {
        if (v?.gene) variantsByGene[v.gene.toUpperCase()] = { genotype: v.genotype_called, gene: v.gene }
      }
    }
    const activeForms = activeGenomeFormsFromContext({ variantsByGene })
    let phenotypes = null
    try { phenotypes = g ? inferAllPGxPhenotypes(g) : null } catch { /* noop */ }
    setContext({ activeForms, phenotypes })
  }, [open])

  const hasGenome = context.activeForms.length > 0

  // Close on Escape key
  useEffect(() => {
    if (!open || typeof window === 'undefined') return
    const onKey = (e) => { if (e.key === 'Escape') onClose() }
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [open, onClose])

  // Enrich each item with brand + BrandScore + interaction flags.
  const enriched = useMemo(() => {
    const userDrugs = (meds || []).map((m) => m.name)
    return items.map((it) => {
      const brand = Object.values(BRAND_PROFILES).find(
        (b) => b.slug === it.brandSlug || b.name === it.brand,
      )
      let bs = null
      let extras = null
      if (brand) {
        extras = getBrandExtras(brand.slug)
        bs = computeBrandScore(brand, extras, hasGenome ? context.activeForms : null)
      }
      const interactions = findInteractionsForSupplement(it.name, {
        userDrugs,
        phenotypes: context.phenotypes,
      })
      const monthlyCost = extras ? (COST_TO_MONTHLY[extras.costTier] ?? 30) : 30
      return { ...it, brand, extras, bs, interactions, monthlyCost }
    })
  }, [items, meds, hasGenome, context])

  // Overall stack quality (mirrors the widget calc).
  const agg = useMemo(() => {
    if (enriched.length === 0) return null
    let trustSum = 0, trustCount = 0, genSum = 0, genCount = 0, cost = 0
    for (const it of enriched) {
      if (it.bs) {
        trustSum += it.bs.overall; trustCount++
        if (it.bs.subScores.genomics != null) { genSum += it.bs.subScores.genomics; genCount++ }
      }
      cost += it.monthlyCost
    }
    const brandTrust = trustCount ? trustSum / trustCount : 0
    const genomeAlign = genCount ? genSum / genCount : 0
    const overall = Math.round(brandTrust * 6 + genomeAlign * 4)
    const tier = overall >= 80 ? 'high' : overall >= 50 ? 'moderate' : 'low'
    return { overall, brandTrust, genomeAlign, cost, tier }
  }, [enriched])

  const copyStack = () => {
    const lines = ['My SelfScience Supplement Stack', '─'.repeat(30), '']
    for (const it of enriched) {
      lines.push(`• ${it.name}${it.brand ? ` — ${it.brand.name}` : ''}`)
      if (it.form) lines.push(`   Form: ${it.form}`)
      if (it.dose) lines.push(`   Dose: ${it.dose}`)
      if (it.timing) lines.push(`   Timing: ${it.timing}`)
      if (it.interactions?.length) {
        for (const flag of it.interactions) {
          lines.push(`   ⚠ ${flag.message}`)
        }
      }
      lines.push('')
    }
    if (agg) {
      lines.push('─'.repeat(30))
      lines.push(`Stack quality: ${agg.overall}/100`)
      lines.push(`Estimated cost: ~$${agg.cost}/month`)
    }
    lines.push('')
    lines.push('Generated by SelfScience — Educational use only, not a clinical test.')
    try {
      navigator.clipboard.writeText(lines.join('\n'))
      setCopied(true)
      setTimeout(() => setCopied(false), 1500)
    } catch { /* noop */ }
  }

  if (!open) return null

  return (
    <div
      className="fixed inset-0 z-50 flex items-end justify-end bg-black/40 sm:items-stretch"
      onClick={onClose}
      role="dialog"
      aria-modal="true"
      aria-label="My supplement stack"
    >
      <div
        onClick={(e) => e.stopPropagation()}
        className="flex h-[92vh] w-full max-w-md flex-col rounded-t-2xl bg-white shadow-2xl sm:h-full sm:rounded-none sm:rounded-l-2xl"
      >
        <header className="flex items-center justify-between border-b border-ss-border-warm/60 px-4 py-3">
          <div>
            <div className="text-[10px] font-extrabold uppercase tracking-[0.16em] text-ss-teal">
              My stack
            </div>
            <div className="text-sm font-bold text-ss-text">{items.length} supplement{items.length === 1 ? '' : 's'}</div>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="flex h-11 w-11 items-center justify-center rounded-full text-ss-muted hover:bg-ss-bg"
            aria-label="Close"
          >
            <X size={16} />
          </button>
        </header>

        <div className="flex-1 overflow-y-auto p-4">
          {enriched.length === 0 ? (
            <div className="mt-8 text-center">
              <span className="mx-auto flex h-12 w-12 items-center justify-center rounded-full bg-ss-teal/10 text-ss-teal">
                <Sparkles size={20} />
              </span>
              <p className="mt-3 text-sm font-semibold text-ss-text">Your stack is empty</p>
              <p className="mt-1 text-[12px] text-ss-muted">
                Tap "Add to my stack" on any supplement card in the discovery view or brand leaderboard to start building your stack.
              </p>
              <Link
                href="/tools/supplements"
                className="mt-4 inline-flex min-h-11 items-center gap-1.5 rounded-full bg-ss-teal px-4 text-sm font-bold text-white hover:brightness-110"
              >
                Browse supplements
              </Link>
            </div>
          ) : (
            <>
              {/* Aggregate summary */}
              {agg && (
                <div className="rounded-xl border border-ss-border-warm/60 bg-ss-bg/50 p-3">
                  <div className="text-[10px] font-extrabold uppercase tracking-[0.16em] text-ss-teal">
                    Stack quality
                  </div>
                  <div className="mt-1 flex items-baseline gap-2">
                    <span className={`tabular-nums text-3xl font-black ${
                      agg.tier === 'high' ? 'text-emerald-700' :
                      agg.tier === 'moderate' ? 'text-amber-700' : 'text-red-700'
                    }`}>{agg.overall}</span>
                    <span className="text-xs font-bold text-ss-muted">/ 100</span>
                    <span className={`ml-auto rounded-full px-2 py-0.5 text-[10px] font-bold uppercase tracking-wider border ${BRAND_SCORE_STYLE[agg.tier].chip}`}>
                      {BRAND_SCORE_STYLE[agg.tier].label}
                    </span>
                  </div>
                  <div className="mt-2 grid grid-cols-3 gap-2 text-center text-[11px]">
                    <div className="rounded bg-white px-1.5 py-1">
                      <div className="text-[9px] font-bold uppercase text-ss-muted">Brand trust</div>
                      <div className="font-black text-ss-teal">{agg.brandTrust.toFixed(1)}<span className="text-[9px] text-ss-muted">/10</span></div>
                    </div>
                    {hasGenome && (
                      <div className="rounded bg-white px-1.5 py-1">
                        <div className="text-[9px] font-bold uppercase text-ss-muted">Genome</div>
                        <div className="font-black text-emerald-700">{agg.genomeAlign.toFixed(1)}<span className="text-[9px] text-ss-muted">/10</span></div>
                      </div>
                    )}
                    <div className="rounded bg-white px-1.5 py-1">
                      <div className="text-[9px] font-bold uppercase text-ss-muted">Est. cost</div>
                      <div className="font-black text-ss-text">${agg.cost}<span className="text-[9px] text-ss-muted">/mo</span></div>
                    </div>
                  </div>
                </div>
              )}

              {/* Item list */}
              <ul className="mt-4 space-y-2.5">
                {enriched.map((it) => (
                  <li key={it.id} className="rounded-xl border border-ss-border-warm/60 bg-white p-3 shadow-sm">
                    <div className="flex items-start justify-between gap-2">
                      <div className="min-w-0 flex-1">
                        <div className="text-sm font-bold text-ss-text">{it.name}</div>
                        {it.brand && (
                          <div className="mt-0.5 flex flex-wrap items-center gap-1.5 text-[11px]">
                            <span className="text-ss-muted">{it.brand.name}</span>
                            {it.bs && (
                              <span className={`rounded-full px-1.5 py-0.5 text-[10px] font-bold border ${BRAND_SCORE_STYLE[it.bs.tier].chip}`}>
                                {it.bs.overall.toFixed(1)} /10
                              </span>
                            )}
                            {it.extras?.costTier && (
                              <span className="rounded-full bg-slate-100 px-1.5 py-0.5 text-[10px] font-bold text-slate-700">
                                {it.extras.costTier}
                              </span>
                            )}
                          </div>
                        )}
                        {(it.dose || it.timing) && (
                          <div className="mt-1 text-[11px] text-ss-muted">
                            {it.dose ? <>{it.dose}</> : null}
                            {it.dose && it.timing ? ' · ' : null}
                            {it.timing ? <>{it.timing}</> : null}
                          </div>
                        )}
                      </div>
                      <button
                        type="button"
                        onClick={() => stackStore.remove(it.id)}
                        className="flex h-9 w-9 items-center justify-center rounded-full text-ss-muted hover:bg-ss-bg hover:text-ss-red"
                        aria-label={`Remove ${it.name}`}
                      >
                        <Trash2 size={13} />
                      </button>
                    </div>

                    {it.interactions.length > 0 && (
                      <div className="mt-2 rounded-lg border border-ss-amber/40 bg-ss-amber/10 p-2">
                        <div className="flex items-center gap-1 text-[10px] font-extrabold uppercase tracking-wider text-ss-amber">
                          <AlertTriangle size={10} /> Interaction flag
                        </div>
                        {it.interactions.map((flag, i) => (
                          <p key={i} className="mt-1 text-[11.5px] leading-snug text-ss-text">
                            {flag.message}
                          </p>
                        ))}
                      </div>
                    )}

                    {it.brand?.officialUrl && (
                      <a
                        href={it.brand.officialUrl}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="mt-2 inline-flex min-h-9 items-center gap-1 text-[11px] font-semibold text-ss-orange hover:underline"
                      >
                        Brand store <ExternalLink size={10} />
                      </a>
                    )}
                  </li>
                ))}
              </ul>

              <p className="mt-4 text-[10px] italic text-ss-muted">
                For educational purposes only. Not a substitute for professional medical advice.
              </p>
            </>
          )}
        </div>

        {enriched.length > 0 && (
          <footer className="border-t border-ss-border-warm/60 bg-white p-3">
            <div className="flex gap-2">
              <button
                type="button"
                onClick={copyStack}
                className="inline-flex min-h-11 flex-1 items-center justify-center gap-1.5 rounded-full border border-ss-teal bg-white px-4 text-sm font-bold text-ss-teal hover:bg-ss-teal hover:text-white"
              >
                {copied ? <><CheckCircle2 size={13} /> Copied</> : <><Copy size={13} /> Export stack</>}
              </button>
              <button
                type="button"
                onClick={() => { if (confirm('Clear your whole stack?')) stackStore.clear() }}
                className="inline-flex min-h-11 items-center gap-1.5 rounded-full border border-ss-border-warm px-3 text-sm font-semibold text-ss-muted hover:text-ss-red"
              >
                <Trash2 size={13} />
              </button>
            </div>
          </footer>
        )}
      </div>
    </div>
  )
}

// A tiny "Add to stack" button re-usable on any product/brand card.
export function AddToStackButton({ item, className = '', label = 'Add to my stack' }) {
  const [mounted, setMounted] = useState(false)
  const [tick, setTick] = useState(0)
  useEffect(() => {
    setMounted(true)
    return stackStore.subscribe(() => setTick((t) => t + 1))
  }, [])
  const inStack = mounted && stackStore.findBy(
    (i) =>
      (item.id && i.id === item.id) ||
      (item.name && item.brand && i.name === item.name && i.brand === item.brand),
  )
  const handle = () => {
    if (inStack) stackStore.remove(inStack.id)
    else stackStore.add(item)
  }
  return (
    <button
      type="button"
      onClick={handle}
      className={`inline-flex min-h-9 items-center gap-1 rounded-full px-3 py-1.5 text-[11px] font-bold transition ${
        inStack
          ? 'bg-emerald-600 text-white hover:bg-emerald-700'
          : 'border border-ss-teal text-ss-teal hover:bg-ss-teal hover:text-white'
      } ${className}`}
    >
      {inStack ? <><CheckCircle2 size={12} /> In stack</> : <><Sparkles size={12} /> {label}</>}
    </button>
  )
}
